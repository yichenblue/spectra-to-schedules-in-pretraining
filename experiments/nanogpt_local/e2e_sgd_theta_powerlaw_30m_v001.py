def schedule_manifest() -> Json:
    """Return the frozen schedule/tape/accounting manifest and its digest."""

    unsigned = _schedule_manifest_unsigned()
    return {**unsigned, "sha256": _canonical_sha256(unsigned)}


def _schedule_manifest_sha256_is_compatible(value: Any) -> bool:
    return (
        type(value) is str
        and (
            value == schedule_manifest()["sha256"]
            or value in LEGACY_SCHEDULE_MANIFEST_SHA256S
        )
    )


def _require_exact_model(config: Mapping[str, Any]) -> None:
    model = _mapping(config.get("model"), "model")
    for key in ("family", "block_size", "vocab_size", "dropout", "bias"):
        if model.get(key) != MODEL_SPEC[key] or type(model.get(key)) is not type(
            MODEL_SPEC[key]
        ):
            raise ThetaPowerlawError(f"model.{key} changed")
    aliases = {
        "expected_parameter_count": ("expected_parameter_count", "parameters"),
        "n_layer": ("n_layer", "layers"),
        "n_head": ("n_head", "heads"),
        "n_embd": ("n_embd", "embedding"),
    }
    for expected_key, keys in aliases.items():
        value = next((model[key] for key in keys if key in model), None)
        if type(value) is not int or value != MODEL_SPEC[expected_key]:
            raise ThetaPowerlawError(f"model.{expected_key} changed")


def _require_plain_sgd(config: Mapping[str, Any]) -> None:
    optimizer = _mapping(config.get("optimizer"), "optimizer")
    expected = {
        "name": "sgd",
        "momentum": 0.0,
        "dampening": 0.0,
        "nesterov": False,
        "weight_decay": 0.0,
        "gradient_clip": 0.0,
        "foreach": False,
    }
    for key, value in expected.items():
        if optimizer.get(key) != value or type(optimizer.get(key)) is not type(value):
            raise ThetaPowerlawError(f"optimizer.{key} changed")
    learning_rate = optimizer.get("learning_rate", optimizer.get("eta0"))
    if type(learning_rate) is not float or learning_rate != ETA0:
        raise ThetaPowerlawError(f"optimizer learning rate must equal {ETA0!r}")
    if optimizer.get("batch_size", BATCH_SIZE) != BATCH_SIZE:
        raise ThetaPowerlawError("optimizer.batch_size must equal 8")


def _validate_config(config: Mapping[str, Any]) -> None:
    if config.get("schema_version") != CONFIG_SCHEMA:
        raise ThetaPowerlawError(f"schema_version must equal {CONFIG_SCHEMA!r}")
    identity = config.get("campaign_id", config.get("run_id"))
    if identity != CAMPAIGN_ID:
        raise ThetaPowerlawError(f"run/campaign id must equal {CAMPAIGN_ID!r}")
    if config.get("primary_prediction_id") != PRIMARY_PREDICTION_ID:
        raise ThetaPowerlawError("primary_prediction_id must be A2_EXTERNAL")
    if "stage" in config and config["stage"] != STAGE:
        raise ThetaPowerlawError(f"stage must equal {STAGE!r}")

    launch = _mapping(config.get("launch_control", {}), "launch_control")
    if launch.get("cluster_submission_authorized") is not False:
        raise ThetaPowerlawError("core config must remain submission-unauthorized")
    if launch.get("runner_has_no_submission_capability", True) is not True:
        raise ThetaPowerlawError("core must declare no submission capability")
    scope = _mapping(config.get("scientific_scope", {}), "scientific_scope")
    if scope.get("theorem_facing") is not False:
        raise ThetaPowerlawError("end-to-end experiment cannot be theorem-facing")
    if scope.get("evidence_class", PRIMARY_PREDICTION_ID) != PRIMARY_PREDICTION_ID:
        raise ThetaPowerlawError("scientific_scope.evidence_class changed")

    data = _mapping(config.get("data"), "data")
    for role in ("train", "validation"):
        record = _mapping(data.get(role), f"data.{role}")
        if type(record.get("path")) is not str or not record["path"]:
            raise ThetaPowerlawError(f"data.{role}.path is absent")
        if not _is_hex64(record.get("sha256")):
            raise ThetaPowerlawError(f"data.{role}.sha256 is not frozen")
        if record.get("dtype") not in ("uint16", "uint16_le"):
            raise ThetaPowerlawError(f"data.{role}.dtype must be uint16")
        if type(record.get("token_count")) is not int:
            raise ThetaPowerlawError(f"data.{role}.token_count is absent")
        if record.get("size_bytes", 2 * record["token_count"]) != 2 * record[
            "token_count"
        ]:
            raise ThetaPowerlawError(f"data.{role}.size_bytes changed")
    if data["train"]["token_count"] != CORPUS_TOKENS:
        raise ThetaPowerlawError("the exact 2.5B-token training corpus is required")
    probe = _mapping(data.get("validation_probe"), "data.validation_probe")
    if (
        type(probe.get("path")) is not str
        or not probe["path"]
        or not _is_hex64(probe.get("sha256"))
        or probe.get("dtype") not in ("int64", "int64_le")
        or probe.get("context_count", probe.get("count")) != VALIDATION_CONTEXTS
    ):
        raise ThetaPowerlawError("the fixed 1024-context validation probe changed")

    _require_exact_model(config)
    _require_plain_sgd(config)

    design = _mapping(config.get("design"), "design")
    exact_design = {
        "batch_size": BATCH_SIZE,
        "aligned_stride": ALIGNED_STRIDE,
        "prefix_updates": PREFIX_UPDATES,
        "initialization_seed": INITIALIZATION_SEED,
        "training_tape_seed": TRAINING_TAPE_SEED,
        "validation_batch_size": VALIDATION_BATCH_SIZE,
    }
    for key, expected in exact_design.items():
        value = design.get(key, design.get("source_update") if key == "prefix_updates" else None)
        if value != expected or type(value) is not type(expected):
            raise ThetaPowerlawError(f"design.{key} must equal {expected!r}")
    optional_design = {
        "block_size": BLOCK_SIZE,
        "tau_scale_updates": 1_024,
        "terminal_x": TERMINAL_X,
        "evaluation_x_count": len(TARGET_X),
    }
    for key, expected in optional_design.items():
        if key in design and (
            design[key] != expected or type(design[key]) is not type(expected)
        ):
            raise ThetaPowerlawError(f"design.{key} must equal {expected!r}")
    if list(design.get("theta_grid", THETAS)) != list(THETAS):
        raise ThetaPowerlawError(f"design.theta_grid must equal {list(THETAS)!r}")
    if "tau_scale" in design and design["tau_scale"] != TAU_SCALE:
        raise ThetaPowerlawError("design.tau_scale changed")
    if "tau_max" in design and design["tau_max"] != TAU_MAX:
        raise ThetaPowerlawError("design.tau_max changed")
    if "target_x" in design and list(design["target_x"]) != TARGET_X.tolist():
        raise ThetaPowerlawError("design.target_x changed")

    runtime = _mapping(config.get("runtime"), "runtime")
    runtime_expected = {
        "dtype": "float32",
        "amp": False,
        "tf32": False,
        "compile": False,
        "deterministic": True,
    }
    for key, expected in runtime_expected.items():
        if runtime.get(key) != expected or type(runtime.get(key)) is not type(expected):
            raise ThetaPowerlawError(f"runtime.{key} changed")
    device_name = runtime.get("training_device", runtime.get("device"))
    if device_name != "cuda":
        raise ThetaPowerlawError("runtime training device must be cuda")
    if runtime.get("preflight_device", "cpu") != "cpu":
        raise ThetaPowerlawError("runtime.preflight_device must be cpu")
    if runtime.get("microbatch_size", BATCH_SIZE) != BATCH_SIZE:
        raise ThetaPowerlawError("runtime.microbatch_size must equal 8")
    if runtime.get("grad_accum_steps", 1) != 1:
        raise ThetaPowerlawError("runtime.grad_accum_steps must equal 1")
    for key in ("maximum_wall_seconds", "maximum_gpu_hours"):
        if key in runtime and (
            type(runtime[key]) not in (int, float)
            or type(runtime[key]) is bool
            or not math.isfinite(float(runtime[key]))
            or float(runtime[key]) <= 0.0
        ):
            raise ThetaPowerlawError(f"runtime.{key} must be positive and finite")

    artifacts = _mapping(config.get("artifacts", {}), "artifacts")
    expected_names = {
        "result": RESULT_FILENAME,
        "training_trace": TRACE_FILENAME,
        "validation_evaluations": VALIDATION_FILENAME,
        "prefix_checkpoint": CHECKPOINT_FILENAME,
    }
    for key, expected in expected_names.items():
        if artifacts.get(key, expected) != expected:
            raise ThetaPowerlawError(f"artifacts.{key} must equal {expected!r}")


def _load_inputs(
    config: Mapping[str, Any],
) -> tuple[np.memmap, np.memmap, np.ndarray, np.ndarray, Json]:
    data = config["data"]
    train, train_info = cooldown._load_uint16_stream(data["train"], "train")
    validation, validation_info = cooldown._load_uint16_stream(
        data["validation"], "validation"
    )
    probe, probe_info = cooldown._load_validation_probe(
        data["validation_probe"], len(validation)
    )
    if int(np.max(train)) >= VOCAB_SIZE or int(np.max(validation)) >= VOCAB_SIZE:
        raise ThetaPowerlawError("token id exceeds the frozen vocabulary")
    tape = make_training_tape(len(train))
    info = {
        "train": train_info,
        "validation": validation_info,
        "validation_probe": probe_info,
    }
    return train, validation, probe, tape, info


def _data_identity_sha256(data_info: Mapping[str, Any]) -> str:
    return _canonical_sha256(
        {
            role: {
                key: record[key]
                for key in ("sha256", "token_count", "bytes")
                if key in record
            }
            for role, record in data_info.items()
        }
    )


def _tape_manifest(tape: np.ndarray) -> Json:
    if (
        tape.shape != (PREFIX_UPDATES + MAX_TAIL_UPDATES, BATCH_SIZE)
        or tape.dtype != np.dtype(np.int64)
    ):
        raise ThetaPowerlawError("training tape shape or dtype changed")
    return {
        "algorithm": "legacy 700M tape plus disjoint 2.5B-region extension",
        "seed": TRAINING_TAPE_SEED,
        "extension_seed": TRAINING_TAPE_EXTENSION_SEED,
        "eligible_aligned_starts": _eligible_aligned_starts(CORPUS_TOKENS),
        "shape": list(tape.shape),
        "unique_contexts": int(tape.size),
        "training_tape_sha256": _array_sha256(tape),
        "prefix_tape_sha256": _array_sha256(tape[:PREFIX_UPDATES]),
        "future_tape_sha256": _array_sha256(tape[PREFIX_UPDATES:]),
        "used_future_tape_sha256_by_theta": {
            _theta_tag(theta): _used_future_tape_sha256(tape, theta)
            for theta in THETAS
        },
    }


def _configure_runtime(config: Mapping[str, Any]) -> torch.device:
    cooldown._configure_deterministic_cuda()
    runtime = config["runtime"]
    device = b0.resolve_device(str(runtime.get("training_device", runtime.get("device"))))
    if device.type != "cuda":
        raise ThetaPowerlawError("training execution requires CUDA")
    required = str(runtime.get("required_device_name_substring", ""))
    device_name = torch.cuda.get_device_name(device)
    if required and required.lower() not in device_name.lower():
        raise ThetaPowerlawError(
            f"CUDA device {device_name!r} does not contain {required!r}"
        )
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.backends.cudnn.benchmark = False
    return device


def _maximum_wall_seconds(config: Mapping[str, Any]) -> float:
    return float(config["runtime"].get("maximum_wall_seconds", 21_600.0))


def _maximum_gpu_hours(config: Mapping[str, Any]) -> float:
    return float(config["runtime"].get("maximum_gpu_hours", 8.0))


def _check_deadline(deadline: float) -> None:
    if time.monotonic() >= deadline:
        raise ThetaPowerlawError("maximum_wall_seconds_reached")


def _progress(phase: str, completed: int, total: int, started: float) -> None:
    elapsed = time.monotonic() - started
    print(
        json.dumps(
            {
                "kind": "progress",
                "phase": phase,
                "completed_updates": completed,
                "total_updates": total,
                "elapsed_seconds": elapsed,
            },
            sort_keys=True,
        ),
        file=sys.stderr,
        flush=True,
    )


def _prepare_output(output_dir: str | Path, phase: str) -> Path:
    output = Path(output_dir).expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    names = [RESULT_FILENAME, TRACE_FILENAME, VALIDATION_FILENAME]
    if phase == "prefix":
        names.append(CHECKPOINT_FILENAME)
    for name in names:
        path = output / name
        temporary = output / f"{name}.part"
        if path.exists() or path.is_symlink() or temporary.exists() or temporary.is_symlink():
            raise ThetaPowerlawError(f"refusing to replace artifact: {path}")
    return output


def _atomic_json(path: Path, value: Mapping[str, Any]) -> None:
    raw = json.dumps(
        value,
        indent=2,
        sort_keys=True,
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8") + b"\n"
    temporary = path.with_name(path.name + ".part")
    with temporary.open("xb") as stream:
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


def _atomic_npz(path: Path, arrays: Mapping[str, np.ndarray]) -> None:
    temporary = path.with_name(path.name + ".part")
    with temporary.open("xb") as stream:
        np.savez_compressed(stream, **arrays)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


def _atomic_checkpoint(path: Path, value: Mapping[str, Any]) -> None:
    temporary = path.with_name(path.name + ".part")
    with temporary.open("xb") as stream:
        torch.save(dict(value), stream)
        stream.flush()
        os.fsync(stream.fileno())
    checked = torch.load(temporary, map_location="cpu", weights_only=True)
    _validate_checkpoint_payload(checked)
    os.replace(temporary, path)


