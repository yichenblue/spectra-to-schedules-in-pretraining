def _validate_checkpoint_payload(
    value: Any,
    *,
    data_identity_sha256: str | None = None,
    validation_probe_sha256: str | None = None,
) -> Mapping[str, Any]:
    if type(value) is not dict:
        raise ThetaPowerlawError("prefix checkpoint root must be an object")
    expected = {
        "schema_version": CHECKPOINT_SCHEMA,
        "campaign_id": CAMPAIGN_ID,
        "run_id": RUN_ID,
        "model_config": {
            "block_size": BLOCK_SIZE,
            "vocab_size": VOCAB_SIZE,
            "n_layer": 6,
            "n_head": 6,
            "n_embd": 384,
            "dropout": 0.0,
            "bias": False,
        },
        "model_state_sha256": EXPECTED_PREFIX_STATE_SHA256,
        "optimizer_state_entries": 0,
        "initialization_seed": INITIALIZATION_SEED,
        "training_tape_seed": TRAINING_TAPE_SEED,
        "prefix_tape_sha256": EXPECTED_PREFIX_TAPE_SHA256,
        "completed_updates": PREFIX_UPDATES,
        "prefix_updates": PREFIX_UPDATES,
        "tape_context_cursor": PREFIX_CONTEXTS,
        "tokens_seen": PREFIX_TOKENS,
        "prefix_intrinsic_time": PREFIX_INTRINSIC_TIME,
    }
    current_lineage = (
        value.get("schedule_manifest_sha256") == schedule_manifest()["sha256"]
        and value.get("training_tape_sha256") == EXPECTED_TRAINING_TAPE_SHA256
        and value.get("future_tape_sha256") == EXPECTED_FUTURE_TAPE_SHA256
    )
    legacy_lineage = (
        value.get("schedule_manifest_sha256")
        in LEGACY_SCHEDULE_MANIFEST_SHA256S
        and value.get("training_tape_sha256") == LEGACY_TRAINING_TAPE_SHA256
        and value.get("future_tape_sha256") == LEGACY_FUTURE_TAPE_SHA256
    )
    if (
        not (current_lineage or legacy_lineage)
        or any(
            value.get(key) != expected_value
            for key, expected_value in expected.items()
        )
    ):
        raise ThetaPowerlawError("prefix checkpoint metadata changed")
    if data_identity_sha256 is not None:
        if data_identity_sha256 != EXPANDED_DATA_IDENTITY_SHA256:
            raise ThetaPowerlawError("active expanded data identity changed")
        if not (
            value.get("data_identity_sha256") == data_identity_sha256
            or (
                legacy_lineage
                and value.get("data_identity_sha256")
                == LEGACY_DATA_IDENTITY_SHA256
            )
        ):
            raise ThetaPowerlawError("prefix checkpoint data identity changed")
    if validation_probe_sha256 is not None and value.get("validation_probe_sha256") != validation_probe_sha256:
        raise ThetaPowerlawError("prefix checkpoint validation probe changed")
    state = value.get("model_state")
    if type(state) is not dict or not state:
        raise ThetaPowerlawError("prefix checkpoint model state is absent")
    for name, tensor in state.items():
        if (
            type(name) is not str
            or not isinstance(tensor, torch.Tensor)
            or tensor.device.type != "cpu"
            or not bool(torch.all(torch.isfinite(tensor)))
        ):
            raise ThetaPowerlawError(f"invalid checkpoint tensor: {name!r}")
    state_sha256 = cooldown._state_dict_sha256(state)
    if state_sha256 != EXPECTED_PREFIX_STATE_SHA256:
        raise ThetaPowerlawError(
            "prefix state hash does not reproduce the prior mature lineage"
        )
    anchor = value.get("prefix_validation_context_cross_entropies")
    if (
        not isinstance(anchor, torch.Tensor)
        or anchor.device.type != "cpu"
        or anchor.dtype != torch.float32
        or tuple(anchor.shape) != (VALIDATION_CONTEXTS,)
        or not bool(torch.all(torch.isfinite(anchor)))
    ):
        raise ThetaPowerlawError("prefix checkpoint validation anchor changed")
    anchor_hash = _array_sha256(anchor.numpy())
    if anchor_hash != value.get("prefix_validation_sha256"):
        raise ThetaPowerlawError("prefix checkpoint validation anchor hash changed")
    rng_state = value.get("rng_state")
    if not isinstance(rng_state, Mapping):
        raise ThetaPowerlawError("prefix checkpoint RNG state is absent")
    if cooldown._rng_state_sha256(rng_state) != value.get("rng_state_sha256"):
        raise ThetaPowerlawError("prefix checkpoint RNG state hash changed")
    return value


def _load_prefix_checkpoint(
    path: str | Path,
    *,
    data_identity_sha256: str,
    validation_probe_sha256: str,
) -> Mapping[str, Any]:
    checkpoint_path = Path(path).expanduser().resolve()
    if not checkpoint_path.is_file() or checkpoint_path.is_symlink():
        raise ThetaPowerlawError(f"prefix checkpoint is absent or linked: {checkpoint_path}")
    value = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    return _validate_checkpoint_payload(
        value,
        data_identity_sha256=data_identity_sha256,
        validation_probe_sha256=validation_probe_sha256,
    )


def preflight(
    config_or_path: str | Path | Mapping[str, Any],
    output_dir: str | Path | None = None,
) -> Json:
    """Perform CPU-only data, tape, schedule, model, and SGD checks."""

    started = time.monotonic()
    config = _load_config(config_or_path)
    _validate_config(config)
    train, validation, probe, tape, data_info = _load_inputs(config)
    model = cooldown._new_model(config, torch.device("cpu"))
    optimizer = b0._build_optimizer(model, ETA0)
    tape_info = _tape_manifest(tape)
    schedule = schedule_manifest()
    checks = {
        "data_hashes_and_counts": True,
        "model_parameter_count_exact": sum(p.numel() for p in model.parameters())
        == MODEL_SPEC["expected_parameter_count"],
        "embedding_and_head_tied": model.lm_head.weight.data_ptr()
        == model.transformer.wte.weight.data_ptr(),
        "plain_sgd_state_empty": not optimizer.state_dict()["state"],
        "all_five_tail_update_counts_exact": all(
            len(_tail_schedule(theta)["update"]) == EXPECTED_TAIL_UPDATES[theta]
            for theta in THETAS
        ),
        "common_exact_tail_endpoint": all(
            _tail_schedule(theta)["tail_intrinsic_time_after"][-1] == TAU_MAX
            and _tail_schedule(theta)["schedule_coordinate_x_after"][-1]
            == TERMINAL_X
            for theta in THETAS
        ),
        "common_validation_target_count_exact": all(
            len(_evaluation_updates(theta))
            == len(TARGET_X)
            == VALIDATION_EVALUATION_COUNT
            for theta in THETAS
        ),
        "frozen_tape_hashes": tape_info["training_tape_sha256"]
        == EXPECTED_TRAINING_TAPE_SHA256
        and tape_info["prefix_tape_sha256"] == EXPECTED_PREFIX_TAPE_SHA256
        and tape_info["future_tape_sha256"] == EXPECTED_FUTURE_TAPE_SHA256,
        "without_replacement": int(np.unique(tape).size) == tape.size,
        "longest_tail_fits_expanded_corpus": _eligible_aligned_starts(len(train))
        >= TAPE_CONTEXTS,
        "validation_probe_unique_and_in_bounds": len(np.unique(probe))
        == len(probe)
        == VALIDATION_CONTEXTS,
        "no_submission_capability": True,
    }
    result: Json = {
        "schema_version": PREFLIGHT_SCHEMA,
        "campaign_id": CAMPAIGN_ID,
        "status": "passed" if all(checks.values()) else "failed",
        "scope": {
            "prediction_id": PRIMARY_PREDICTION_ID,
            "evidence_class": PRIMARY_PREDICTION_ID,
            "theorem_facing": False,
        },
        "config_sha256": config["_config_hash"],
        "schedule_manifest_sha256": schedule["sha256"],
        "checks": checks,
        "data": data_info,
        "training_tape": tape_info,
        "model": MODEL_SPEC,
        "optimizer": _optimizer_result(len(optimizer.state_dict()["state"])),
        "elapsed_seconds": time.monotonic() - started,
        "scientific_training_executed": False,
        "gpu_submission_performed": False,
    }
    del optimizer, model, tape, probe, validation, train
    if output_dir is not None:
        output = Path(output_dir).expanduser().resolve()
        output.mkdir(parents=True, exist_ok=True)
        _atomic_json(output / "preflight.json", result)
    return result


def _prefix_trace_arrays(losses: np.ndarray) -> dict[str, np.ndarray]:
    update = np.arange(1, PREFIX_UPDATES + 1, dtype=np.int64)
    intrinsic = update.astype(np.float64) * ETA0
    return {
        "schema_version": np.asarray(TRACE_SCHEMA),
        "phase": np.asarray("prefix"),
        "update": update,
        "learning_rate": np.full(PREFIX_UPDATES, ETA0, dtype=np.float64),
        "prefix_intrinsic_time_after": intrinsic,
        "tau": intrinsic,
        "X": 1.0 + intrinsic / TAU_SCALE,
        "tokens_seen": update * TOKENS_PER_UPDATE,
        "training_cross_entropy": np.ascontiguousarray(losses, dtype=np.float32),
    }


def _prefix_validation_arrays(anchor: np.ndarray) -> dict[str, np.ndarray]:
    contexts = np.ascontiguousarray(anchor, dtype=np.float32).reshape(
        1, VALIDATION_CONTEXTS
    )
    return {
        "schema_version": np.asarray(VALIDATION_SCHEMA),
        "phase": np.asarray("prefix"),
        "target_x": np.asarray([1.0], dtype=np.float64),
        "actual_x": np.asarray([1.0], dtype=np.float64),
        "update": np.asarray([PREFIX_UPDATES], dtype=np.int64),
        "tail_intrinsic_time": np.asarray([0.0], dtype=np.float64),
        "prefix_intrinsic_time": np.asarray([PREFIX_INTRINSIC_TIME], dtype=np.float64),
        "tokens_seen": np.asarray([PREFIX_TOKENS], dtype=np.int64),
        "validation_cross_entropy": np.asarray(
            [np.mean(contexts[0], dtype=np.float64)], dtype=np.float64
        ),
        "context_cross_entropies": contexts,
    }


def run_prefix(
    config_or_path: str | Path | Mapping[str, Any],
    output_dir: str | Path,
) -> Json:
    """Recreate and persist the exact mature prefix once."""

    config = _load_config(config_or_path)
    _validate_config(config)
    output = _prepare_output(output_dir, "prefix")
    started = time.monotonic()
    result = _common_result(config, phase="prefix", theta=None)
    device: torch.device | None = None
    peak_memory_bytes: int | None = None
    completed = 0
    try:
        train, validation, probe, tape, data_info = _load_inputs(config)
        result["data"] = data_info
        result["data_identity_sha256"] = _data_identity_sha256(data_info)
        result["validation_probe_offsets_sha256"] = _array_sha256(probe)
        device = _configure_runtime(config)
        torch.cuda.reset_peak_memory_stats(device)
        model = cooldown._new_model(config, device)
        optimizer = b0._build_optimizer(model, ETA0)
        losses = np.empty(PREFIX_UPDATES, dtype=np.float32)
        deadline = started + _maximum_wall_seconds(config)
        for index in range(PREFIX_UPDATES):
            _check_deadline(deadline)
            losses[index] = cooldown._training_step(
                model, optimizer, train, tape[index], device, ETA0
            )
            completed = index + 1
            if completed % 4_096 == 0:
                _progress("prefix", completed, PREFIX_UPDATES, started)
        if not np.all(np.isfinite(losses)) or optimizer.state_dict()["state"]:
            raise ThetaPowerlawError("prefix loss or plain-SGD state invariant failed")

        state = cooldown._capture_cpu_snapshot(model)
        state_sha256 = cooldown._state_dict_sha256(state)
        if state_sha256 != EXPECTED_PREFIX_STATE_SHA256:
            raise ThetaPowerlawError(
                "prefix state hash mismatch: "
                f"observed {state_sha256}, expected {EXPECTED_PREFIX_STATE_SHA256}"
            )
        rng_state = cooldown._capture_rng_state(device)
        anchor = cooldown._evaluate_contexts(
            model, validation, probe, device, VALIDATION_BATCH_SIZE
        )
        anchor_sha256 = _array_sha256(anchor)
        checkpoint = {
            "schema_version": CHECKPOINT_SCHEMA,
            "campaign_id": CAMPAIGN_ID,
            "run_id": RUN_ID,
            "config_sha256": config["_config_hash"],
            "schedule_manifest_sha256": schedule_manifest()["sha256"],
            "model_config": asdict(cooldown._model_config(config)),
            "model_state": state,
            "model_state_sha256": state_sha256,
            "optimizer_state_entries": len(optimizer.state_dict()["state"]),
            "initialization_seed": INITIALIZATION_SEED,
            "training_tape_seed": TRAINING_TAPE_SEED,
            "training_tape_sha256": EXPECTED_TRAINING_TAPE_SHA256,
            "prefix_tape_sha256": EXPECTED_PREFIX_TAPE_SHA256,
            "future_tape_sha256": EXPECTED_FUTURE_TAPE_SHA256,
            "data_identity_sha256": result["data_identity_sha256"],
            "validation_probe_sha256": result["validation_probe_sha256"],
            "validation_probe_offsets_sha256": result[
                "validation_probe_offsets_sha256"
            ],
            "completed_updates": PREFIX_UPDATES,
            "prefix_updates": PREFIX_UPDATES,
            "tape_context_cursor": PREFIX_CONTEXTS,
            "tokens_seen": PREFIX_TOKENS,
            "prefix_intrinsic_time": PREFIX_INTRINSIC_TIME,
            "prefix_validation_context_cross_entropies": torch.from_numpy(
                anchor.copy()
            ),
            "prefix_validation_sha256": anchor_sha256,
            "validation_anchor_sha256": anchor_sha256,
            "rng_state": rng_state,
            "rng_state_sha256": cooldown._rng_state_sha256(rng_state),
        }

        checkpoint_path = output / CHECKPOINT_FILENAME
        trace_path = output / TRACE_FILENAME
        validation_path = output / VALIDATION_FILENAME
        _atomic_checkpoint(checkpoint_path, checkpoint)
        _atomic_npz(trace_path, _prefix_trace_arrays(losses))
        _atomic_npz(validation_path, _prefix_validation_arrays(anchor))
        peak_memory_bytes = int(torch.cuda.max_memory_allocated(device))

        result["status"] = "completed"
        result["validation_anchor_sha256"] = anchor_sha256
        result["prefix_checkpoint_sha256"] = b0.sha256_file(checkpoint_path)
        result["counts"] = {
            "prefix_updates": PREFIX_UPDATES,
            "tail_updates": 0,
            "total_updates": PREFIX_UPDATES,
            "prefix_tokens": PREFIX_TOKENS,
            "tail_tokens": 0,
            "total_tokens": PREFIX_TOKENS,
            "validation_evaluations": 1,
        }
        result["artifacts"] = {
            "training_trace": _artifact_record(trace_path),
            "validation_evaluations": _artifact_record(validation_path),
            "prefix_checkpoint": _artifact_record(checkpoint_path),
        }
        del optimizer, model, state
        torch.cuda.empty_cache()
    except Exception as error:
        result["failure"] = _failure(error)
        result["counts"] = {
            "planned_prefix_updates": PREFIX_UPDATES,
            "completed_prefix_updates": completed,
        }

    runtime = _runtime_record(
        device=device, started=started, peak_memory_bytes=peak_memory_bytes
    )
    result["runtime"] = runtime
    result["resource"] = _resource_record(config, runtime)
    if result["status"] == "completed" and not result["resource"]["budget_passed"]:
        result["status"] = "incomplete"
        result["failure"] = {
            "type": "ThetaPowerlawError",
            "message": "resource_budget_exceeded",
            "traceback_tail": [],
        }
    _atomic_json(output / RESULT_FILENAME, result)
    if result["status"] == "completed":
        validate_artifacts(output / RESULT_FILENAME, require_complete=True)
    return result


def _tail_trace_arrays(
    theta: float,
    losses: np.ndarray,
) -> dict[str, np.ndarray]:
    schedule = _tail_schedule(theta)
    return {
        "schema_version": np.asarray(TRACE_SCHEMA),
        "phase": np.asarray("tail"),
        "theta": np.asarray(theta, dtype=np.float64),
        **{key: np.ascontiguousarray(value) for key, value in schedule.items()},
        "training_cross_entropy": np.ascontiguousarray(losses, dtype=np.float32),
    }


def _tail_validation_arrays(
    theta: float,
    contexts: Sequence[np.ndarray],
) -> dict[str, np.ndarray]:
    schedule = _tail_schedule(theta)
    updates = _evaluation_updates(theta)
    context_matrix = np.ascontiguousarray(np.stack(contexts), dtype=np.float32)
    actual_x = np.empty(len(updates), dtype=np.float64)
    tau = np.empty(len(updates), dtype=np.float64)
    tokens = np.empty(len(updates), dtype=np.int64)
    actual_x[0] = 1.0
    tau[0] = 0.0
    tokens[0] = PREFIX_TOKENS
    actual_x[1:] = schedule["schedule_coordinate_x_after"][updates[1:] - 1]
    tau[1:] = schedule["tail_intrinsic_time_after"][updates[1:] - 1]
    tokens[1:] = schedule["tokens_seen"][updates[1:] - 1]
    return {
        "schema_version": np.asarray(VALIDATION_SCHEMA),
        "phase": np.asarray("tail"),
        "theta": np.asarray(theta, dtype=np.float64),
        "target_x": TARGET_X.copy(),
        "actual_x": actual_x,
        "update": updates,
        "tail_intrinsic_time": tau,
        "tokens_seen": tokens,
        "validation_cross_entropy": np.mean(
            context_matrix, axis=1, dtype=np.float64
        ),
        "context_cross_entropies": context_matrix,
    }


def run_tail(
    config_or_path: str | Path | Mapping[str, Any],
    checkpoint_path: str | Path,
    output_dir: str | Path,
    theta: float,
) -> Json:
    """Run one frozen theta arm from the exact common prefix checkpoint."""

    theta = _theta(theta)
    config = _load_config(config_or_path)
    _validate_config(config)
    output = _prepare_output(output_dir, "tail")
    started = time.monotonic()
    result = _common_result(config, phase="tail", theta=theta)
    device: torch.device | None = None
    peak_memory_bytes: int | None = None
    completed = 0
    try:
        train, validation, probe, tape, data_info = _load_inputs(config)
        result["data"] = data_info
        data_identity = _data_identity_sha256(data_info)
        result["data_identity_sha256"] = data_identity
        result["validation_probe_offsets_sha256"] = _array_sha256(probe)
        checkpoint_path = Path(checkpoint_path).expanduser().resolve()
        checkpoint = _load_prefix_checkpoint(
            checkpoint_path,
            data_identity_sha256=data_identity,
            validation_probe_sha256=result["validation_probe_sha256"],
        )
        result["prefix_checkpoint_sha256"] = b0.sha256_file(checkpoint_path)
        result["validation_anchor_sha256"] = checkpoint[
            "validation_anchor_sha256"
        ]
        result["used_future_tape_sha256"] = _used_future_tape_sha256(tape, theta)

        device = _configure_runtime(config)
        torch.cuda.reset_peak_memory_stats(device)
        model = cooldown._new_model(config, device)
        model.load_state_dict(checkpoint["model_state"], strict=True)
        restored_sha256 = cooldown._state_dict_sha256(
            cooldown._capture_cpu_snapshot(model)
        )
        if restored_sha256 != EXPECTED_PREFIX_STATE_SHA256:
            raise ThetaPowerlawError("tail did not restore the exact mature state")
        cooldown._restore_rng_state(checkpoint["rng_state"], device)
        optimizer = b0._build_optimizer(model, ETA0)
        if optimizer.state_dict()["state"]:
            raise ThetaPowerlawError("tail optimizer did not begin with empty state")

        anchor = cooldown._evaluate_contexts(
            model, validation, probe, device, VALIDATION_BATCH_SIZE
        )
        if _array_sha256(anchor) != checkpoint["prefix_validation_sha256"]:
            raise ThetaPowerlawError("tail reload changed the fixed-probe prefix anchor")
        contexts: list[np.ndarray] = [anchor]
        schedule = _tail_schedule(theta)
        evaluation_updates = _evaluation_updates(theta)
        evaluation_set = set(int(value) for value in evaluation_updates[1:])
        losses = np.empty(EXPECTED_TAIL_UPDATES[theta], dtype=np.float32)
        deadline = started + _maximum_wall_seconds(config)
        for index in range(EXPECTED_TAIL_UPDATES[theta]):
            _check_deadline(deadline)
            learning_rate = float(schedule["learning_rate"][index])
            losses[index] = cooldown._training_step(
                model,
                optimizer,
                train,
                tape[PREFIX_UPDATES + index],
                device,
                learning_rate,
            )
            completed = index + 1
            if completed in evaluation_set:
                contexts.append(
                    cooldown._evaluate_contexts(
                        model, validation, probe, device, VALIDATION_BATCH_SIZE
                    )
                )
            if completed % 4_096 == 0:
                _progress(_theta_tag(theta), completed, len(losses), started)

        if (
            len(contexts) != len(TARGET_X)
            or not np.all(np.isfinite(losses))
            or optimizer.state_dict()["state"]
        ):
            raise ThetaPowerlawError("tail completion invariant failed")
        terminal_state_sha256 = cooldown._state_dict_sha256(
            cooldown._capture_cpu_snapshot(model)
        )
        trace_path = output / TRACE_FILENAME
        validation_path = output / VALIDATION_FILENAME
        _atomic_npz(trace_path, _tail_trace_arrays(theta, losses))
        _atomic_npz(validation_path, _tail_validation_arrays(theta, contexts))
        peak_memory_bytes = int(torch.cuda.max_memory_allocated(device))

        tail_updates = EXPECTED_TAIL_UPDATES[theta]
        tail_tokens = tail_updates * TOKENS_PER_UPDATE
        result["status"] = "completed"
        result["terminal_state_sha256"] = terminal_state_sha256
        result["counts"] = {
            "prefix_updates": PREFIX_UPDATES,
            "tail_updates": tail_updates,
            "total_updates": PREFIX_UPDATES + tail_updates,
            "prefix_tokens": PREFIX_TOKENS,
            "tail_tokens": tail_tokens,
            "total_tokens": PREFIX_TOKENS + tail_tokens,
            "validation_evaluations": len(TARGET_X),
            "validation_contexts_per_evaluation": VALIDATION_CONTEXTS,
        }
        result["artifacts"] = {
            "training_trace": _artifact_record(trace_path),
            "validation_evaluations": _artifact_record(validation_path),
        }
        del optimizer, model
        torch.cuda.empty_cache()
    except Exception as error:
        result["failure"] = _failure(error)
        result["counts"] = {
            "planned_tail_updates": EXPECTED_TAIL_UPDATES[theta],
            "completed_tail_updates": completed,
        }

    runtime = _runtime_record(
        device=device, started=started, peak_memory_bytes=peak_memory_bytes
    )
    result["runtime"] = runtime
    result["resource"] = _resource_record(config, runtime)
    if result["status"] == "completed" and not result["resource"]["budget_passed"]:
        result["status"] = "incomplete"
        result["failure"] = {
            "type": "ThetaPowerlawError",
            "message": "resource_budget_exceeded",
            "traceback_tail": [],
        }
    _atomic_json(output / RESULT_FILENAME, result)
    if result["status"] == "completed":
        validate_artifacts(output / RESULT_FILENAME, require_complete=True)
    return result


def _load_result_and_root(
    result_or_path: str | Path | Mapping[str, Any],
    artifact_dir: str | Path | None,
) -> tuple[Json, Path]:
    if isinstance(result_or_path, (str, Path)):
        path = Path(result_or_path).expanduser().resolve()
        if path.is_dir():
            path = path / RESULT_FILENAME
        with path.open("r", encoding="utf-8") as stream:
            result = json.load(stream)
        root = path.parent
    else:
        result = copy.deepcopy(dict(result_or_path))
        if artifact_dir is None:
            raise ThetaPowerlawError("artifact_dir is required for an in-memory result")
        root = Path(artifact_dir).expanduser().resolve()
    if type(result) is not dict:
        raise ThetaPowerlawError("result JSON root must be an object")
    return result, root


def _verify_artifact(root: Path, record: Any, label: str) -> Path:
    record = _mapping(record, f"artifacts.{label}")
    if set(record) != {"path", "sha256", "size_bytes"}:
        raise ThetaPowerlawError(f"artifacts.{label} fields changed")
    if Path(str(record["path"])).name != record["path"]:
        raise ThetaPowerlawError(f"artifacts.{label}.path is not a basename")
    path = root / str(record["path"])
    if (
        not path.is_file()
        or path.is_symlink()
        or path.stat().st_size != int(record["size_bytes"])
        or b0.sha256_file(path) != record["sha256"]
    ):
        raise ThetaPowerlawError(f"artifacts.{label} bytes changed")
    return path


def _npz_text(archive: Mapping[str, np.ndarray], key: str) -> str:
    value = archive[key]
    if value.shape != ():
        raise ThetaPowerlawError(f"NPZ scalar {key} changed")
    return str(value.item())


def _validate_prefix_npz(trace_path: Path, validation_path: Path) -> str:
    with np.load(trace_path, allow_pickle=False) as trace:
        required = {
            "schema_version",
            "phase",
            "update",
            "learning_rate",
            "prefix_intrinsic_time_after",
            "tau",
            "X",
            "tokens_seen",
            "training_cross_entropy",
        }
        if not required.issubset(trace.files):
            raise ThetaPowerlawError("prefix training trace columns are incomplete")
        update = np.arange(1, PREFIX_UPDATES + 1, dtype=np.int64)
        intrinsic = update.astype(np.float64) * ETA0
        if (
            _npz_text(trace, "schema_version") != TRACE_SCHEMA
            or _npz_text(trace, "phase") != "prefix"
            or not np.array_equal(trace["update"], update)
            or not np.array_equal(
                trace["learning_rate"],
                np.full(PREFIX_UPDATES, ETA0, dtype=np.float64),
            )
            or not np.array_equal(trace["prefix_intrinsic_time_after"], intrinsic)
            or not np.array_equal(trace["tau"], intrinsic)
            or not np.array_equal(trace["X"], 1.0 + intrinsic / TAU_SCALE)
            or not np.array_equal(trace["tokens_seen"], update * TOKENS_PER_UPDATE)
            or trace["training_cross_entropy"].shape != (PREFIX_UPDATES,)
            or trace["training_cross_entropy"].dtype != np.float32
            or not np.all(np.isfinite(trace["training_cross_entropy"]))
        ):
            raise ThetaPowerlawError("prefix training trace failed replay validation")
    with np.load(validation_path, allow_pickle=False) as evaluations:
        required = {
            "schema_version",
            "phase",
            "target_x",
            "actual_x",
            "update",
            "tail_intrinsic_time",
            "tokens_seen",
            "validation_cross_entropy",
            "context_cross_entropies",
        }
        if not required.issubset(evaluations.files):
            raise ThetaPowerlawError("prefix validation columns are incomplete")
        contexts = evaluations["context_cross_entropies"]
        mean = np.mean(contexts, axis=1, dtype=np.float64)
        if (
            _npz_text(evaluations, "schema_version") != VALIDATION_SCHEMA
            or _npz_text(evaluations, "phase") != "prefix"
            or contexts.shape != (1, VALIDATION_CONTEXTS)
            or contexts.dtype != np.float32
            or not np.all(np.isfinite(contexts))
            or not np.array_equal(evaluations["validation_cross_entropy"], mean)
            or not np.array_equal(evaluations["target_x"], [1.0])
            or not np.array_equal(evaluations["actual_x"], [1.0])
            or not np.array_equal(evaluations["update"], [PREFIX_UPDATES])
            or not np.array_equal(evaluations["tail_intrinsic_time"], [0.0])
            or not np.array_equal(evaluations["tokens_seen"], [PREFIX_TOKENS])
        ):
            raise ThetaPowerlawError("prefix validation artifact failed validation")
        return _array_sha256(contexts[0])


def _validate_tail_npz(
    theta: float,
    trace_path: Path,
    validation_path: Path,
) -> str:
    schedule = _tail_schedule(theta)
    with np.load(trace_path, allow_pickle=False) as trace:
        required = {
            "schema_version",
            "phase",
            "theta",
            *schedule.keys(),
            "training_cross_entropy",
        }
        if not required.issubset(trace.files):
            raise ThetaPowerlawError("tail training trace columns are incomplete")
        if (
            _npz_text(trace, "schema_version") != TRACE_SCHEMA
            or _npz_text(trace, "phase") != "tail"
            or trace["theta"].shape != ()
            or float(trace["theta"]) != theta
            or any(not np.array_equal(trace[key], value) for key, value in schedule.items())
            or trace["training_cross_entropy"].shape
            != (EXPECTED_TAIL_UPDATES[theta],)
            or trace["training_cross_entropy"].dtype != np.float32
            or not np.all(np.isfinite(trace["training_cross_entropy"]))
        ):
            raise ThetaPowerlawError("tail training trace failed schedule replay")
    with np.load(validation_path, allow_pickle=False) as evaluations:
        required = {
            "schema_version",
            "phase",
            "theta",
            "target_x",
            "actual_x",
            "update",
            "tail_intrinsic_time",
            "tokens_seen",
            "validation_cross_entropy",
            "context_cross_entropies",
        }
        if not required.issubset(evaluations.files):
            raise ThetaPowerlawError("tail validation columns are incomplete")
        updates = _evaluation_updates(theta)
        expected_x = np.empty(len(updates), dtype=np.float64)
        expected_tau = np.empty(len(updates), dtype=np.float64)
        expected_tokens = np.empty(len(updates), dtype=np.int64)
        expected_x[0], expected_tau[0], expected_tokens[0] = 1.0, 0.0, PREFIX_TOKENS
        expected_x[1:] = schedule["schedule_coordinate_x_after"][updates[1:] - 1]
        expected_tau[1:] = schedule["tail_intrinsic_time_after"][updates[1:] - 1]
        expected_tokens[1:] = schedule["tokens_seen"][updates[1:] - 1]
        contexts = evaluations["context_cross_entropies"]
        means = np.mean(contexts, axis=1, dtype=np.float64)
        first_crossing = np.concatenate(
            (np.asarray([1.0]), schedule["schedule_coordinate_x_after"][updates[1:] - 1])
        )
        previous_x = np.concatenate(
            (np.asarray([-np.inf]), schedule["schedule_coordinate_x_before"][updates[1:] - 1])
        )
        if (
            _npz_text(evaluations, "schema_version") != VALIDATION_SCHEMA
            or _npz_text(evaluations, "phase") != "tail"
            or evaluations["theta"].shape != ()
            or float(evaluations["theta"]) != theta
            or not np.array_equal(evaluations["target_x"], TARGET_X)
            or not np.array_equal(evaluations["actual_x"], expected_x)
            or not np.array_equal(evaluations["update"], updates)
            or not np.array_equal(evaluations["tail_intrinsic_time"], expected_tau)
            or not np.array_equal(evaluations["tokens_seen"], expected_tokens)
            or contexts.shape != (len(TARGET_X), VALIDATION_CONTEXTS)
            or contexts.dtype != np.float32
            or not np.all(np.isfinite(contexts))
            or not np.array_equal(evaluations["validation_cross_entropy"], means)
            or np.any(first_crossing[1:] < TARGET_X[1:])
            or np.any(previous_x[1:] >= TARGET_X[1:])
        ):
            raise ThetaPowerlawError("tail validation artifact failed replay validation")
        return _array_sha256(contexts[0])


def validate_artifacts(
    result_or_path: str | Path | Mapping[str, Any],
    *,
    artifact_dir: str | Path | None = None,
    require_complete: bool = True,
) -> Json:
    """Validate hashes plus all deterministic NPZ/checkpoint coordinates."""

    result, root = _load_result_and_root(result_or_path, artifact_dir)
    if (
        result.get("schema_version") != RESULT_SCHEMA
        or result.get("campaign_id") != CAMPAIGN_ID
        or result.get("run_id") != RUN_ID
        or result.get("scope")
        != {
            "prediction_id": PRIMARY_PREDICTION_ID,
            "evidence_class": PRIMARY_PREDICTION_ID,
            "theorem_facing": False,
        }
        or not _schedule_manifest_sha256_is_compatible(
            result.get("schedule_manifest_sha256")
        )
        or result.get("prefix_state_sha256") != EXPECTED_PREFIX_STATE_SHA256
        or result.get("training_tape_sha256") != EXPECTED_TRAINING_TAPE_SHA256
        or result.get("prefix_tape_sha256") != EXPECTED_PREFIX_TAPE_SHA256
        or result.get("future_tape_sha256") != EXPECTED_FUTURE_TAPE_SHA256
        or not _is_hex64(result.get("validation_probe_sha256"))
        or result.get("gpu_submission_performed") is not False
    ):
        raise ThetaPowerlawError("result identity or frozen hashes changed")
    if result.get("status") not in ("completed", "incomplete"):
        raise ThetaPowerlawError("result status must be completed or incomplete")
    if require_complete and result["status"] != "completed":
        raise ThetaPowerlawError("result is incomplete")
    if result["status"] == "incomplete":
        return {
            "schema_version": RESULT_SCHEMA,
            "campaign_id": CAMPAIGN_ID,
            "status": "incomplete",
            "valid": True,
        }

    artifacts = _mapping(result.get("artifacts"), "artifacts")
    trace_path = _verify_artifact(root, artifacts.get("training_trace"), "training_trace")
    validation_path = _verify_artifact(
        root, artifacts.get("validation_evaluations"), "validation_evaluations"
    )
    phase = result.get("phase")
    if phase == "prefix":
        if result.get("theta") is not None:
            raise ThetaPowerlawError("prefix result cannot select theta")
        checkpoint_path = _verify_artifact(
            root, artifacts.get("prefix_checkpoint"), "prefix_checkpoint"
        )
        checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
        _validate_checkpoint_payload(checkpoint)
        anchor_hash = _validate_prefix_npz(trace_path, validation_path)
        expected_counts = {
            "prefix_updates": PREFIX_UPDATES,
            "tail_updates": 0,
            "total_updates": PREFIX_UPDATES,
            "prefix_tokens": PREFIX_TOKENS,
            "tail_tokens": 0,
            "total_tokens": PREFIX_TOKENS,
            "validation_evaluations": 1,
        }
        if (
            result.get("counts") != expected_counts
            or result.get("prefix_checkpoint_sha256") != b0.sha256_file(checkpoint_path)
            or result.get("validation_anchor_sha256") != anchor_hash
            or checkpoint.get("validation_anchor_sha256") != anchor_hash
        ):
            raise ThetaPowerlawError("prefix result/checkpoint accounting changed")
    elif phase == "tail":
        theta = _theta(result.get("theta"))
        anchor_hash = _validate_tail_npz(theta, trace_path, validation_path)
        updates = EXPECTED_TAIL_UPDATES[theta]
        tail_tokens = updates * TOKENS_PER_UPDATE
        expected_counts = {
            "prefix_updates": PREFIX_UPDATES,
            "tail_updates": updates,
            "total_updates": PREFIX_UPDATES + updates,
            "prefix_tokens": PREFIX_TOKENS,
            "tail_tokens": tail_tokens,
            "total_tokens": PREFIX_TOKENS + tail_tokens,
            "validation_evaluations": len(TARGET_X),
            "validation_contexts_per_evaluation": VALIDATION_CONTEXTS,
        }
        if (
            result.get("counts") != expected_counts
            or result.get("terminal_tail_intrinsic_time") != TAU_MAX
            or result.get("terminal_schedule_coordinate_x") != TERMINAL_X
            or result.get("validation_anchor_sha256") != anchor_hash
            or not _is_hex64(result.get("prefix_checkpoint_sha256"))
            or not _is_hex64(result.get("used_future_tape_sha256"))
        ):
            raise ThetaPowerlawError("tail result accounting or anchor changed")
    else:
        raise ThetaPowerlawError("result phase must be prefix or tail")
    return {
        "schema_version": RESULT_SCHEMA,
        "campaign_id": CAMPAIGN_ID,
        "phase": phase,
        "theta": result.get("theta"),
        "status": "completed",
        "valid": True,
    }


def validate_result(
    result_or_path: str | Path | Mapping[str, Any],
    *,
    artifact_dir: str | Path | None = None,
    require_complete: bool = True,
) -> Json:
    """Compatibility alias for callers that name result validation directly."""

    return validate_artifacts(
        result_or_path,
        artifact_dir=artifact_dir,
        require_complete=require_complete,
    )


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--preflight", action="store_true")
    modes.add_argument("--run-prefix", action="store_true")
    modes.add_argument("--run-tail", action="store_true")
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--theta", type=float)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_argument_parser()
    args = parser.parse_args(argv)
    try:
        if args.preflight:
            if args.checkpoint is not None or args.theta is not None:
                parser.error("--preflight does not accept --checkpoint or --theta")
            result = preflight(args.config, output_dir=args.output_dir)
        elif args.run_prefix:
            if args.output_dir is None:
                parser.error("--run-prefix requires --output-dir")
            if args.checkpoint is not None or args.theta is not None:
                parser.error("--run-prefix does not accept --checkpoint or --theta")
            result = run_prefix(args.config, args.output_dir)
        else:
            if args.output_dir is None or args.checkpoint is None or args.theta is None:
                parser.error(
                    "--run-tail requires --theta, --checkpoint, and --output-dir"
                )
            result = run_tail(
                args.config, args.checkpoint, args.output_dir, args.theta
            )
    except (OSError, RuntimeError, ValueError) as error:
        print(
            json.dumps(
                {"status": "incomplete", "error": str(error)},
                sort_keys=True,
                allow_nan=False,
            )
        )
        return 2
    print(json.dumps(result, sort_keys=True, ensure_ascii=False, allow_nan=False))
    return 0 if result.get("status") in ("passed", "completed") else 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
