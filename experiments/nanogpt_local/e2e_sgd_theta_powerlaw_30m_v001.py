class ThetaPowerlawError(RuntimeError):
    """A frozen schedule, data, checkpoint, or runtime invariant failed."""


def _canonical_sha256(value: Any) -> str:
    raw = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def _array_sha256(value: np.ndarray) -> str:
    array = np.ascontiguousarray(value)
    return hashlib.sha256(array.tobytes(order="C")).hexdigest()


def _is_hex64(value: Any) -> bool:
    return bool(
        type(value) is str
        and len(value) == 64
        and all(character in "0123456789abcdef" for character in value)
    )


def _mapping(value: Any, label: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise ThetaPowerlawError(f"{label} must be a JSON object")
    return value


def _clean_config(config: Mapping[str, Any]) -> Json:
    return {key: value for key, value in config.items() if not key.startswith("_")}


def _load_config(config_or_path: str | Path | Mapping[str, Any]) -> Json:
    if isinstance(config_or_path, (str, Path)):
        return b0.load_config(config_or_path)
    config = copy.deepcopy(dict(config_or_path))
    config["_config_hash"] = _canonical_sha256(_clean_config(config))
    return config


def _theta(value: Any) -> float:
    if type(value) not in (int, float) or type(value) is bool:
        raise ThetaPowerlawError("theta must be numeric")
    result = float(value)
    if result not in THETAS:
        raise ThetaPowerlawError(f"theta must be one of {list(THETAS)!r}")
    return result


def _theta_tag(theta: float) -> str:
    return {
        0.0: "theta0",
        0.5: "theta0p5",
        0.75: "theta0p75",
        1.0: "theta1",
        1.5: "theta1p5",
    }[_theta(theta)]


def _eligible_aligned_starts(token_count: int) -> int:
    if token_count < BLOCK_SIZE + 1:
        return 0
    return (int(token_count) - (BLOCK_SIZE + 1)) // ALIGNED_STRIDE + 1


@lru_cache(maxsize=None)
def _tail_schedule(theta_value: float) -> Mapping[str, np.ndarray]:
    """Return the exact discrete schedule, including the sole terminal edit."""

    theta = _theta(theta_value)
    nominal_rates: list[float] = []
    rates: list[float] = []
    tau_before: list[float] = []
    tau_after: list[float] = []
    x_before: list[float] = []
    x_after: list[float] = []
    terminal_edit: list[bool] = []
    tau = 0.0
    expected_updates = EXPECTED_TAIL_UPDATES[theta]

    while True:
        before_x = 1.0 + tau / TAU_SCALE
        nominal = ETA0 * before_x ** (-theta)
        remaining = TAU_MAX - tau
        terminal = remaining <= nominal + FINAL_RATE_TOLERANCE
        actual = remaining if terminal else nominal
        after_tau = TAU_MAX if terminal else tau + actual
        after_x = TERMINAL_X if terminal else 1.0 + after_tau / TAU_SCALE
        if (
            not all(math.isfinite(value) for value in (nominal, actual, after_tau))
            or nominal <= 0.0
            or actual <= 0.0
            or after_tau <= tau
            or actual > nominal + FINAL_RATE_TOLERANCE
        ):
            raise ThetaPowerlawError("invalid discrete tail schedule")

        nominal_rates.append(nominal)
        rates.append(actual)
        tau_before.append(tau)
        tau_after.append(after_tau)
        x_before.append(before_x)
        x_after.append(after_x)
        terminal_edit.append(bool(actual != nominal))
        if terminal:
            break
        tau = after_tau
        if len(rates) >= expected_updates:
            raise ThetaPowerlawError("tail failed to reach its terminal intrinsic time")

    arrays: dict[str, np.ndarray] = {
        "update": np.arange(1, len(rates) + 1, dtype=np.int64),
        "learning_rate": np.asarray(rates, dtype=np.float64),
        "nominal_learning_rate": np.asarray(nominal_rates, dtype=np.float64),
        "tail_intrinsic_time_before": np.asarray(tau_before, dtype=np.float64),
        "tail_intrinsic_time_after": np.asarray(tau_after, dtype=np.float64),
        "schedule_coordinate_x_before": np.asarray(x_before, dtype=np.float64),
        "schedule_coordinate_x_after": np.asarray(x_after, dtype=np.float64),
        "terminal_eta_truncated": np.asarray(terminal_edit, dtype=np.bool_),
    }
    arrays["tokens_seen"] = (
        PREFIX_TOKENS + arrays["update"] * TOKENS_PER_UPDATE
    ).astype(np.int64, copy=False)
    arrays["global_update"] = PREFIX_UPDATES + arrays["update"]

    if len(rates) != expected_updates:
        raise ThetaPowerlawError(
            f"theta={theta} yielded {len(rates)} updates, expected {expected_updates}"
        )
    if not np.array_equal(
        arrays["tail_intrinsic_time_before"][1:],
        arrays["tail_intrinsic_time_after"][:-1],
    ):
        raise ThetaPowerlawError("tail intrinsic-time recurrence is discontinuous")
    if arrays["tail_intrinsic_time_before"][0] != 0.0:
        raise ThetaPowerlawError("tail must begin at tau=0")
    if (
        arrays["tail_intrinsic_time_after"][-1] != TAU_MAX
        or arrays["schedule_coordinate_x_after"][-1] != TERMINAL_X
        or np.any(np.diff(arrays["tail_intrinsic_time_after"]) <= 0.0)
        or np.any(np.diff(arrays["nominal_learning_rate"]) > 0.0)
        or np.any(arrays["terminal_eta_truncated"][:-1])
        or not bool(arrays["terminal_eta_truncated"][-1])
    ):
        raise ThetaPowerlawError("tail endpoint or terminal-edit invariant failed")
    return arrays


def _evaluation_updates(theta: float) -> np.ndarray:
    schedule = _tail_schedule(theta)
    after_x = schedule["schedule_coordinate_x_after"]
    updates = np.zeros(len(TARGET_X), dtype=np.int64)
    updates[1:] = np.searchsorted(after_x, TARGET_X[1:], side="left") + 1
    if (
        updates[0] != 0
        or updates[-1] != EXPECTED_TAIL_UPDATES[_theta(theta)]
        or np.any(np.diff(updates) <= 0)
    ):
        raise ThetaPowerlawError("validation target crossings are not one-to-one")
    return updates


def _used_future_tape_sha256(tape: np.ndarray, theta: float) -> str:
    updates = EXPECTED_TAIL_UPDATES[_theta(theta)]
    return _array_sha256(tape[PREFIX_UPDATES : PREFIX_UPDATES + updates])


def make_training_tape(token_count: int = CORPUS_TOKENS) -> np.ndarray:
    """Build the frozen tape, preserving every established X<=10 row."""

    eligible = _eligible_aligned_starts(int(token_count))
    if eligible < TAPE_CONTEXTS:
        raise ThetaPowerlawError(
            f"corpus exposes {eligible} aligned contexts, need {TAPE_CONTEXTS}"
        )
    legacy_eligible = _eligible_aligned_starts(LEGACY_CORPUS_TOKENS)
    legacy_contexts = (PREFIX_UPDATES + LEGACY_MAX_TAIL_UPDATES) * BATCH_SIZE
    legacy_generator = np.random.Generator(np.random.PCG64(TRAINING_TAPE_SEED))
    legacy_selected = legacy_generator.permutation(legacy_eligible)[:legacy_contexts]
    extra_contexts = TAPE_CONTEXTS - legacy_contexts
    expanded_pool = eligible - legacy_eligible
    if extra_contexts < 0 or expanded_pool < extra_contexts:
        raise ThetaPowerlawError("expanded corpus cannot extend the legacy tape")
    extension_generator = np.random.Generator(
        np.random.PCG64(TRAINING_TAPE_EXTENSION_SEED)
    )
    extension_selected = (
        extension_generator.permutation(expanded_pool)[:extra_contexts]
        + legacy_eligible
    )
    selected = np.concatenate((legacy_selected, extension_selected))
    offsets = np.ascontiguousarray(selected, dtype=np.int64) * ALIGNED_STRIDE
    tape = np.ascontiguousarray(offsets.reshape(-1, BATCH_SIZE))
    if (
        tape.shape != (PREFIX_UPDATES + MAX_TAIL_UPDATES, BATCH_SIZE)
        or _array_sha256(tape) != EXPECTED_TRAINING_TAPE_SHA256
        or _array_sha256(tape[:PREFIX_UPDATES]) != EXPECTED_PREFIX_TAPE_SHA256
        or _array_sha256(tape[PREFIX_UPDATES:]) != EXPECTED_FUTURE_TAPE_SHA256
    ):
        raise ThetaPowerlawError("frozen PCG64 training tape hash changed")
    return tape


